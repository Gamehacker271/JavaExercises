package Ejercicio5;

public class Ejercicio5 {
    public static void main(String[] args) {
        for (int i = 1; i <= 100; i++) {
            if (i % 2 == 0 && i % 3 == 0) {
                System.out.println(i + " es divisible entre 2 y 3");
            } else {
                System.out.println(i + " no es divisible entre 2 y 3");
            }
        }
    }
}

